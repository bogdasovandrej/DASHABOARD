# если причин несколько, берём ту, что выше в этом списке
ORDER = ["leave", "silent", "conflict", "overload", "no_mentor", "no_tasks", "results", "hidden", "low", "formal"]


def first_name(full):
    parts = full.split()
    return parts[1] if len(parts) > 1 else parts[0]  # "Кузнецов Илья" -> "Илья"


def intern_greeting(full):
    s = str(full).strip()
    if not s or ID_CODE.match(s):
        return "Привет! "
    return f"{first_name(s)}, привет! "


def mentor_greeting(mentor):
    s = str(mentor).strip()
    if not s or s.lower() == "не указан" or ID_CODE.match(s):
        return "Добрый день! "
    return f"{s}, добрый день! "


def pick(codes):
    return next((code for code in ORDER if code in codes), "low")


def action(intern, mentor, codes, level, month):
    # Возвращает действие для стажёра в зоне риска или None, если всё спокойно.
    if level == "низкий":
        return None
    code = pick(codes)
    item = PLAYBOOK[code]
    fill = {
        "hello": intern_greeting(intern),
        "mentor_hello": mentor_greeting(mentor),
        "full": intern,
        "month": month,
    }
    return {
        "code": code,
        "title": item["title"],
        "why": item["why"],
        "messages": [(whom, text.format(**fill)) for whom, text in item["messages"]],
    }


def best_quote(com, last_month):
    # Цитата-доказательство: самый свежий комментарий с сигналом, сначала "хочет уйти", сначала слова стажёра.
    # берём только комментарии с сигналом: нейросеть иногда даёт цитату и к обычному комментарию
    c = com[(com["month"] >= last_month - 1) & com["quote"].notna() & com["quote"].ne("") & (com["signals"].map(len) > 0)]
    if c.empty:
        return None
    c = c.assign(
        leave=c["signals"].map(lambda s: "хочет уйти" not in s),
        other=c["role"] != "intern",
    ).sort_values(["leave", "month", "other"], ascending=[True, False, True])
    x = c.iloc[0]
    return {"quote": x["quote"], "text": x["text"], "signals": x["signals"],
            "who": "стажёр" if x["role"] == "intern" else "наставник", "month": int(x["month"])}
